    public static string T(string key) => Strings.TryGetValue(key, out var pair) ? (Language == "fa" ? pair.Fa : pair.En) : key;
    public static void Apply(string language)
    {
        Language = language;
        foreach (var (key, value) in Strings)
            Application.Current.Resources[key] = language == "fa" ? value.Fa : value.En;
        foreach (Window window in Application.Current.Windows)
            window.FlowDirection = language == "fa" ? FlowDirection.RightToLeft : FlowDirection.LeftToRight;
    }
