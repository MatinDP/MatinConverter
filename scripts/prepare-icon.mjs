import sharp from 'sharp';
import fs from 'node:fs/promises';
import path from 'node:path';
const root = process.cwd();
const png = await sharp(path.join(root, 'assets/icon-source.png')).resize(256, 256, { fit: 'contain' }).png().toBuffer();
await fs.writeFile(path.join(root, 'assets/icon.png'), png);
await fs.writeFile(path.join(root, 'public/icon.png'), png);
const header = Buffer.alloc(22);
header.writeUInt16LE(0,0); header.writeUInt16LE(1,2); header.writeUInt16LE(1,4);
header.writeUInt8(0,6); header.writeUInt8(0,7); header.writeUInt8(0,8); header.writeUInt8(0,9);
header.writeUInt16LE(1,10); header.writeUInt16LE(32,12); header.writeUInt32LE(png.length,14); header.writeUInt32LE(22,18);
await fs.writeFile(path.join(root, 'assets/icon.ico'), Buffer.concat([header,png]));
